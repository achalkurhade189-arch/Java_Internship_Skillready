class arithmeticop
{
    public static void main(String args[])
    {
        int a = 10;
        int b = 20;

        System.out.println("Addition : \n"+a+" + "+b+" = "+(a+b));
        System.out.println("Substraction : \n"+a+" - "+b+" = "+(a-b));
        System.out.println("Multiplication : \n"+a+" * "+b+" = "+(a*b));
        System.out.println("Division : \n"+a+" / "+b+" = "+(a/b));
        System.out.println("Reminder : \n"+a+" % "+b+" = "+(a%b));
    }
}
